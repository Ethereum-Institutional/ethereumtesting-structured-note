import type { Addresses } from "@/lib/chain";
import { Panel, Mono, short } from "./ui";

/**
 * Names the stack running underneath the demo, with the deployed addresses to prove it.
 *
 * The product pages say "Meridian Custody" everywhere — a fictional custodian — so without this
 * panel an audience has no way to know that Tokeny, Uniswap and OpenZeppelin are all live on
 * screen, or which layer is doing what. The partnership is the point; it should be legible in
 * the product, not only in the build walkthrough.
 */
export function StackPanel({ a }: { a: Addresses }) {
  const col = (
    title: string,
    tagline: string,
    rows: Array<[string, string | undefined, string]>,
  ) => (
    <div>
      <div className="text-xs font-semibold">{title}</div>
      <div className="mt-0.5 text-[11px]" style={{ color: "var(--muted)" }}>{tagline}</div>
      <dl className="mt-2 space-y-1.5 text-[11px]">
        {rows.map(([name, addr, what]) => (
          <div key={name}>
            <dt className="flex items-baseline justify-between gap-2">
              <span>{name}</span>
              {addr && <Mono title={addr}>{short(addr)}</Mono>}
            </dt>
            <dd style={{ color: "var(--muted)" }}>{what}</dd>
          </div>
        ))}
      </dl>
    </div>
  );

  return (
    <Panel
      title="The stack on screen"
      subtitle="Three partners, one market — every address below is live on this chain"
    >
      <div className="grid gap-5 sm:grid-cols-3">
        {col("Tokeny — the asset", "ERC-3643 (T-REX), the standard behind ~$28bn of tokenized assets", [
          [`${"APMMF"} token`, a.trex.token, "The regulated fund unit; transfers obey its compliance"],
          ["Identity registry", a.trex.identityRegistry, "Who is verified, and under which jurisdiction"],
          ["Modular compliance", a.trex.modularCompliance, "Issuer rules: jurisdictions, supply, limits"],
          ["Trusted claim issuer", a.trex.claimIssuer, "The KYC provider whose signed claims count"],
        ])}
        {col("OpenZeppelin — the layer between", "The part neither partner ships: the rule that lets them interoperate", [
          ["Compliance hook", a.venue.hook, "Gates every swap and LP action in the pool"],
          ["Identity bridge", a.venue.allowlistChecker, "Reads the T-REX registry, answers in Uniswap's permission language"],
          ["Custody accounts", a.custody?.factory, "Segregated client accounts the custodian operates"],
          ["Contracts & tooling", undefined, "OZ Contracts v4 + v5 underneath both sides; token and hook scaffolds generated by OZ's hosted MCPs"],
        ])}
        {col("Uniswap — the venue", "v4 Permissioned Pools (launched July 2026)", [
          ["PoolManager", a.venue.poolManager, "The AMM core"],
          ["Permissions adapter", a.venue.permissionsAdapter, "Custodies the asset; itself a KYC'd holder in the registry"],
          ["Position manager", a.venue.positionManager, "LP positions — non-transferable, issuer can force-exit"],
          ["Permissioned router", a.venue.router, "The approved path for orders"],
        ])}
      </div>
      <p className="mt-4 border-t pt-3 text-[11px] leading-relaxed" style={{ borderColor: "var(--line)", color: "var(--muted)" }}>
        ERC-3643 support in OpenZeppelin Contracts is in active co-development with the T-REX
        Network under the July 2026 partnership. Every enforcement you see in this console — each
        rejected order, each freeze that bites — passes through the OpenZeppelin compliance hook
        before the pool will move a token.
      </p>
    </Panel>
  );
}
